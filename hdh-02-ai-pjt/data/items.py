def load_and_seed_data(db_mgr: DatabaseManager) -> int:
    """104개 항목과 관측치를 SQLite에 멱등하게 적재"""
    with db_mgr.get_connection() as conn:
        cursor = conn.cursor()
        count = 0
        for item in SURVEY_TECHNOLOGY_DATA:
            # 기술 마스터
            cursor.execute(
                """
                INSERT OR REPLACE INTO technology (technology_id, canonical_name, category, description, source_ref)
                VALUES (?, ?, ?, ?, ?)
            """,
                (
                    item["id"],
                    item["name"],
                    item["cat"],
                    item["desc"],
                    "Stack Overflow Developer Survey 2026",
                ),
            )

            # 관측치 레코드 (Usage, Desired, Admired)
            locator = f"survey.stackoverflow.co/2026/technology#{item['cat'].lower()}-{item['id']}"
            cursor.execute(
                """
                INSERT OR REPLACE INTO observation 
                (technology_id, category, year, population_id, usage_pct, desired_pct, admired_pct, question_n, source_locator)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
                (
                    item["id"],
                    item["cat"],
                    2026,
                    "all_respondents",
                    item["usage"],
                    item["desired"],
                    item["admired"],
                    14099,
                    locator,
                ),
            )
            count += 1
        conn.commit()
    return count


