'''
01_dog_api.py - 공개 API 호출 기초 (Dog CEO API)

🎯 학습 목표
    1) requests 로 HTTP 요청을 보낸다.
    2) Response 객체와 JSON(딕셔너리)의 차이를 구분한다.
    3) 딕셔너리에서 필요한 값만 꺼낸다.

📝 결과물
    Dog CEO API 를 호출해 랜덤 강아지 이미지 URL 을 출력한다.

📌 API 정보
    주소  : https://dog.ceo/api/breeds/image/random
    응답  : {'message': '이미지 주소', 'status': 'success'}

📌 비유 - API 호출 = 자판기
    URL(자판기 위치)로 가서 요청(버튼)을 누르면 정해진 규격의 응답(음료)이 나옵니다.
    자판기 사용법(= API 문서)을 모르면 원하는 걸 뽑을 수 없습니다.

[데이터 흐름]
    내 코드 --(요청)--> dog.ceo 서버
    내 코드 <--(JSON 응답)-- dog.ceo 서버
    JSON 문자열 -> .json() -> 파이썬 딕셔너리 -> 원하는 값 추출

📌 실습 TODO : 4개
'''

from pprint import pprint

import requests

# ---------------------------------------------------------------------------
# 1. 요청 보내기
# ---------------------------------------------------------------------------
# [실습 포인트] 자주 바뀌지 않는 값은 상수로 분리합니다. 상수명은 대문자(PEP8).
# TODO 1: 요청할 API 주소를 URL 에 담으세요.
URL = 'https://dog.ceo/api/breeds/image/random'

# [실습 포인트] requests 로 GET 요청을 보냅니다.
#   timeout 을 왜 넣을까? 서버가 응답하지 않으면 프로그램이 영원히 멈추기 때문입니다.
#   실무에서는 timeout 없는 requests 호출을 지양합니다.
# TODO 2: GET 요청을 보내고 결과를 response 에 담으세요.
#   힌트: requests.get(URL, timeout=5)
response = requests.get(URL, timeout=5)


# ---------------------------------------------------------------------------
# 2. 응답 확인 - 여기는 완성되어 있습니다. 출력 결과를 눈으로 확인하세요
# ---------------------------------------------------------------------------
# 200 이면 정상. 4xx/5xx 면 raise_for_status() 가 예외를 던져 문제를 빨리 드러냅니다.
print('상태 코드 :', response.status_code)


# ---------------------------------------------------------------------------
# 3. JSON -> 딕셔너리 변환 후 값 꺼내기
# ---------------------------------------------------------------------------
# [실습 포인트] 응답 본문은 아직 '문자열'입니다.
#   .json() 을 호출해야 파이썬 딕셔너리로 바뀝니다.
#   아래 type() 출력으로 변환 전후의 차이를 직접 확인해 보세요.
# TODO 3: 응답을 딕셔너리로 변환해 data 에 담으세요.
data = response.json()

print('변환 타입 :', type(data))  # <class 'dict'>

print('\n--- 전체 응답 ---')
pprint(data)

# [실습 포인트] 딕셔너리에서 값 꺼내기
#   data['message'] 와 data.get('message') 의 차이는?
#   -> 키가 없을 때 전자는 KeyError, 후자는 None 을 반환합니다.
# TODO 4: 'message' 키의 값을 image_url 에 담으세요.
image_url = data.get('message')
# image_url = data['message']


print('\n--- 추출 결과 ---')
print('강아지 이미지 URL :', image_url)


