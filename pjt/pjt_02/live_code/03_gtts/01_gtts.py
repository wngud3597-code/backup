'''
01_gtts.py - gTTS 로 텍스트를 음성(MP3)으로 변환하기

🎯 학습 목표
    1) gTTS 객체 생성(주문서 작성)과 save() 호출(요청 발송)을 구분한다.
    2) lang / slow 옵션이 결과 음성을 어떻게 바꾸는지 확인한다.

📝 결과물
    원하는 문장을 한국어 음성 mp3 파일로 만들어 직접 들어본다.

📌 gTTS = 길거리 무료 시식
    대본(text)과 요청 사항(언어, 속도)만 넘기면 mp3 를 만들어 돌려줍니다.
    목소리를 고를 수는 없고, 인터넷으로 구글 엔진에 접속하므로
    오프라인에서는 동작하지 않습니다.

설치: pip install gTTS

📌 실습 TODO : 3개
'''

from pathlib import Path

from gtts import gTTS

BASE_DIR = Path(__file__).resolve().parent

# ---------------------------------------------------------------------------
# 1. 대본 준비
# ---------------------------------------------------------------------------
# TODO 1: 음성으로 바꾸고 싶은 문장을 text 에 담으세요.
text = '안녕하세요, gTTS를 이용한 텍스트 음성 변환 예제입니다.'


# ---------------------------------------------------------------------------
# 2. 주문서 작성 (아직 소리는 만들어지지 않습니다)
# ---------------------------------------------------------------------------
# [실습 포인트] gTTS(...) 는 '주문서'를 만드는 단계입니다.
#   text : 변환할 문장
#   lang : 언어 코드 ('ko' 한국어, 'en' 영어, 'ja' 일본어 ...)
#   slow : True 면 느리게 읽습니다.
# TODO 2: gTTS 객체를 생성해 tts 에 담으세요.
#   힌트: gTTS(text=text, lang='ko', slow=False)
tts = gTTS(text=text, lang='ko', slow=False)


# ---------------------------------------------------------------------------
# 3. 저장 (이 순간 구글 서버에 요청이 나갑니다)
# ---------------------------------------------------------------------------
output_path = BASE_DIR / 'output_ko.mp3'

# TODO 3: tts 를 output_path 로 저장하세요.
#   힌트: tts.save(output_path)
tts.save(output_path)

print(f'✅ 저장 완료 : {output_path.name}')
print('   생성된 mp3 파일을 직접 재생해 보세요.')


